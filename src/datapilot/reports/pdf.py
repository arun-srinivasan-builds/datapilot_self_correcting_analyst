"""One-page PDF report (stretch goal 3) built with ReportLab from a verified run.

Inputs are plain data (question, facts, chart PNG bytes, status strings): nothing here talks to the
model, the sandbox or Streamlit. Facts and charts come from the run's validated `results.json`.
"""

from __future__ import annotations

import io
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

MAX_FACTS = 12
MAX_CHARTS = 2
_INK, _MUTED, _RULE = (
    colors.HexColor("#14202b"),
    colors.HexColor("#5b6773"),
    colors.HexColor("#d5dbe1"),
)


@dataclass(frozen=True, slots=True)
class ChartImage:
    title: str
    png: bytes


def _fmt(value: Any, unit: str) -> str:
    if isinstance(value, bool) or not isinstance(value, int | float):
        return str(value)
    text = f"{value:,.0f}" if float(value).is_integer() or abs(value) >= 1000 else f"{value:,.2f}"
    return f"{text} {unit}".strip() if unit else text


def build_pdf(
    *,
    question: str,
    facts: Sequence[dict[str, Any]],
    charts: Sequence[ChartImage],
    reviewer_status: str,
    human_status: str,
    run_id: str,
    dataset_name: str,
    messages: int,
) -> bytes:
    """Render the report. Always one A4 page: facts and charts are capped, images are scaled."""
    base = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=base["Heading1"], fontSize=16, textColor=_INK, spaceAfter=2)
    meta = ParagraphStyle("meta", parent=base["Normal"], fontSize=8, textColor=_MUTED)
    q = ParagraphStyle("q", parent=base["Normal"], fontSize=10, textColor=_INK, spaceAfter=4)
    h2 = ParagraphStyle(
        "h2", parent=base["Heading2"], fontSize=10, textColor=_INK, spaceBefore=6, spaceAfter=3
    )
    cell = ParagraphStyle("cell", parent=base["Normal"], fontSize=8, leading=10, textColor=_INK)
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm,
        topMargin=12 * mm, bottomMargin=12 * mm, title="DataPilot report", author="DataPilot",
    )  # fmt: skip
    story: list[Any] = [
        Paragraph("DataPilot — verified analysis", h1),
        Paragraph(
            escape(f"Dataset: {dataset_name} · run {run_id} · {messages}/12 agent messages"), meta
        ),
        Spacer(1, 4 * mm),
        Paragraph(f"<b>Question.</b> {escape(question[:400])}", q),
        Paragraph(
            f"<b>Reviewer:</b> {escape(reviewer_status)} &nbsp; "
            f"<b>Human:</b> {escape(human_status)}",
            q,
        ),
        Paragraph("Key results", h2),
    ]
    rows = [
        [Paragraph(escape(str(f.get("label", ""))[:120]), cell),
         Paragraph(f"<b>{escape(_fmt(f.get('value', ''), str(f.get('unit', ''))))[:80]}</b>", cell)]
        for f in list(facts)[:MAX_FACTS]
    ]  # fmt: skip
    if rows:
        table = Table(rows, colWidths=[118 * mm, 64 * mm])
        table.setStyle(
            TableStyle(
                [
                    ("LINEBELOW", (0, 0), (-1, -1), 0.25, _RULE),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("TOPPADDING", (0, 0), (-1, -1), 2),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                ]
            )
        )
        story.append(table)
    shown = list(charts)[:MAX_CHARTS]
    if shown:
        story.append(Paragraph("Charts", h2))
        slot_w, slot_h = (182 / len(shown) - 3) * mm, 78 * mm
        images: list[Any] = []
        for chart in shown:
            iw, ih = ImageReader(io.BytesIO(chart.png)).getSize()
            scale = min(slot_w / iw, slot_h / ih)
            images.append(Image(io.BytesIO(chart.png), width=iw * scale, height=ih * scale))
        story.append(Table([images], colWidths=[slot_w + 3 * mm] * len(images)))
    story.append(Spacer(1, 3 * mm))
    story.append(
        Paragraph(
            "Generated by agents (Planner, Coder, Executor, Reviewer) from code executed in an "
            "isolated sandbox. Numbers are the run's results.json; nothing was edited by hand.",
            meta,
        )
    )
    doc.build(story)
    return buffer.getvalue()


def page_count(pdf: bytes) -> int:
    """Number of pages (counts /Type /Page objects; sufficient for ReportLab output)."""
    return pdf.count(b"/Type /Page\n") + pdf.count(b"/Type /Page ") + pdf.count(b"/Type /Page>>")
